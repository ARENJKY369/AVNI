// page composition
// ------------------------------------------------------------------ */

const A4 = { w: 595.28, h: 841.89 };
const MARGIN = { top: 56, bottom: 62, left: 52, right: 52 };
const INK = [0.11, 0.12, 0.14];
const MUTED = [0.42, 0.45, 0.49];
const RULE = [0.78, 0.79, 0.81];
const ACCENT = [0.05, 0.36, 0.42];

const gray = (rgb, [r, g, b]) => rgb(r, g, b);

const wrapText = (text, font, size, width) => {
  const paragraphs = String(text ?? '').split(/\n/);
  const lines = [];
  for (const para of paragraphs) {
    const words = sanitize(para).split(/\s+/).filter(Boolean);
    if (!words.length) {
      lines.push('');
      continue;
    }
    let line = '';
    for (const word of words) {
      const next = line ? `${line} ${word}` : word;
      if (font.widthOfTextAtSize(next, size) <= width) line = next;
      else {
        if (line) lines.push(line);
        line = word;
      }
    }
    if (line) lines.push(line);
  }
  return lines;
};

class Report {
  constructor(doc, fonts, now) {
    this.doc = doc;
    this.f = fonts;
    this.now = now;
    this.pages = [];
    this.newPage();
  }

  newPage() {
    this.page = this.doc.addPage([A4.w, A4.h]);
    this.pages.push(this.page);
    this.y = A4.h - MARGIN.top;
    this.w = A4.w - MARGIN.left - MARGIN.right;
    return this.page;
  }

  need(height) {
    if (this.y - height < MARGIN.bottom) this.newPage();
  }

  text(str, { font = 'body', size = 10, color = INK, x = MARGIN.left, gap = 0, width = this.w } = {}) {
    const f = this.f[font];
    for (const line of wrapText(str, f, size, width)) {
      this.need(size * 1.35);
      this.page.drawText(line, { x, y: this.y - size, size, font: f, color: gray(this.rgb, color) });
      this.y -= size * 1.35;
    }
    this.y -= gap;
  }

  rule({ color = RULE, thickness = 0.6, gap = 8 } = {}) {
    this.need(thickness + gap);
    this.page.drawLine({
      start: { x: MARGIN.left, y: this.y - thickness },
      end: { x: A4.w - MARGIN.right, y: this.y - thickness },
      thickness,
      color: gray(this.rgb, color)
    });
    this.y -= thickness + gap;
  }

  heading(str) {
    this.need(30);
    this.y -= 6;
    this.text(str, { font: 'bold', size: 12.5, color: INK, gap: 3 });
    this.rule({ gap: 9 });
  }

  subheading(str) {
    this.need(20);
    this.y -= 2;
    this.text(str, { font: 'bold', size: 10.5, color: MUTED, gap: 3 });
  }

  /**
   * Label / value rows — the shape most of this document takes. Values are
   * monospaced when they are numbers or coordinates, per the console's own
   * treatment of data.
   */
  rows(items) {
    const labelW = this.w * 0.34;
    for (const row of items) {
      const valueFont = this.f[row.mono === false ? 'body' : 'mono'];
      const size = row.mono === false ? 10 : 9.5;
      const lines = wrapText(row.value, valueFont, size, this.w - labelW);
      this.need(lines.length * size * 1.4 + 6);
      const top = this.y;
      const wrappedLabel = wrapText(row.label, this.f.body, 9.5, labelW - 8);
      wrappedLabel.forEach((line, i) => {
        this.page.drawText(line, {
          x: MARGIN.left,
          y: top - 9.5 - i * 12,
          size: 9.5,
          font: this.f.body,
          color: gray(this.rgb, MUTED)
        });
      });
      lines.forEach((line, i) => {
        this.page.drawText(line, {
          x: MARGIN.left + labelW,
          y: top - size - i * size * 1.4,
          size,
          font: valueFont,
          color: gray(this.rgb, row.color || INK)
        });
      });
      const block = Math.max(wrappedLabel.length * 12, lines.length * size * 1.4);
      this.y = top - block - 5;
    }
  }

  numbered(items) {
    for (const item of items) {
      const size = 9.5;
      const first = wrapText(item.step, this.f.body, size, this.w - 24);
      const second = item.value ? wrapText(item.value, this.f.mono, 9, this.w - 24) : [];
      const sourceLines = wrapText(item.source || '', this.f.mono, 8.5, this.w - 24);
      this.need((first.length + second.length + sourceLines.length) * size * 1.4 + 8);
      const top = this.y;
      this.page.drawText(`${item.n}.`, {
        x: MARGIN.left,
        y: top - size,
        size,
        font: this.f.mono,
        color: gray(this.rgb, MUTED)
      });
      let cursor = top;
      for (const line of first) {
        this.page.drawText(line, { x: MARGIN.left + 18, y: cursor - size, size, font: this.f.body, color: gray(this.rgb, INK) });
        cursor -= size * 1.4;
      }
      for (const line of sourceLines) {
        this.page.drawText(line, { x: MARGIN.left + 18, y: cursor - 8.5, size: 8.5, font: this.f.mono, color: gray(this.rgb, MUTED) });
        cursor -= 8.5 * 1.4;
      }
      for (const line of second) {
        this.page.drawText(line, { x: MARGIN.left + 18, y: cursor - 9, size: 9, font: this.f.mono, color: gray(this.rgb, ACCENT) });
        cursor -= 9 * 1.4;
      }
      this.y = cursor - 4;
    }
  }

  async image(bytes, { caption = null, maxHeight = 300, mediaType = 'image/png' } = {}) {
    const img =
      mediaType === 'image/jpeg' ? await this.doc.embedJpg(bytes) : await this.doc.embedPng(bytes);
    const width = this.w;
    const height = Math.min(maxHeight, (img.height / img.width) * width);
    this.need(height + 18);
    this.page.drawImage(img, { x: MARGIN.left, y: this.y - height, width, height });
    this.page.drawRectangle({
      x: MARGIN.left,
      y: this.y - height,
      width,
      height,
      borderWidth: 0.6,
      borderColor: gray(this.rgb, RULE),
      color: undefined
    });
    this.y -= height + 12;
    if (caption) this.text(caption, { font: 'italic', size: 8.5, color: MUTED, gap: 4 });
  }

  /** Footer on every page, drawn last so it can count the pages. */
  finish() {
    const total = this.pages.length;
    this.pages.forEach((page, i) => {
      page.drawLine({
        start: { x: MARGIN.left, y: MARGIN.bottom - 18 },
        end: { x: A4.w - MARGIN.right, y: MARGIN.bottom - 18 },
        thickness: 0.6,
        color: gray(this.rgb, RULE)
      });
      page.drawText(sanitize(this.noteLine), {
        x: MARGIN.left,
        y: MARGIN.bottom - 32,
        size: 8,
        font: this.f.body,
        color: gray(this.rgb, MUTED)
      });
      const label = `page ${i + 1} of ${total}`;
      page.drawText(label, {
        x: A4.w - MARGIN.right - this.f.mono.widthOfTextAtSize(label, 8),
        y: MARGIN.bottom - 32,
        size: 8,
        font: this.f.mono,
        color: gray(this.rgb, MUTED)
      });
    });
  }
}

/**
 * Compose the document. Returns the PDF bytes; the caller decides what to do
 * with them (the app downloads them, the tests inspect them).
 */
export async function buildReportPdf(model) {
  const { PDFDocument, StandardFonts, rgb } = await import('pdf-lib');
  const doc = await PDFDocument.create();
  doc.setTitle(sanitize(`${REPORT_TITLE} — ${model.question}`));
  doc.setAuthor(REPORT_NOTE.replace('Generated by ', ''));
  doc.setSubject(sanitize(model.question));
  doc.setCreator('AVNI');
  doc.setProducer(`AVNI · ${REPORT_MODEL}`);
  doc.setCreationDate(model.now);

  const fonts = {
    body: await doc.embedFont(StandardFonts.TimesRoman),
    bold: await doc.embedFont(StandardFonts.TimesRomanBold),
    italic: await doc.embedFont(StandardFonts.TimesRomanItalic),
    mono: await doc.embedFont(StandardFonts.Courier),
    monoBold: await doc.embedFont(StandardFonts.CourierBold)
  };

  const r = new Report(doc, fonts, model.now);
  r.rgb = rgb;
  r.noteLine = `${REPORT_NOTE} · ${REPORT_TITLE} · ${model.generatedLabel}`;

  // 1. header block
  r.text(model.title, { font: 'bold', size: 17, gap: 2 });
  r.text(`generated ${model.generatedAt} · ${model.generatedLabel}`, { font: 'mono', size: 8.5, color: MUTED, gap: 6 });
  r.rule({ gap: 12 });
  r.rows(model.header);

  r.heading('Imagery');
  if (model.scenes.length) {
    model.scenes.forEach((s) => {
      r.rows([{ label: s.role, value: s.file }]);
      r.text(`${s.detail ? `${s.detail} · ` : ''}acquired ${s.acquired}`, { font: 'mono', size: 8.5, color: MUTED, gap: 5 });
    });
  } else {
    r.text('no scene registered', { font: 'body', size: 10, color: MUTED });
  }

  // 2. the question and the answer, as prose
  r.heading('Question & answer');
  r.text(model.question, { font: 'bold', size: 11.5, gap: 6 });
  if (model.answer.abstained) {
    r.text(`DECLINED TO ANSWER — consistency below the ${model.answer.gate} gate.`, { font: 'bold', size: 10.5, color: [0.55, 0.35, 0.05], gap: 4 });
    if (model.answer.reason) r.text(model.answer.reason, { gap: 4 });
    r.text('AVNI ran the full pass but held the answer at the gate.', { color: MUTED, gap: 4 });
  } else {
    r.text(model.answer.text || 'no answer text recorded', { size: 10.5, gap: 4 });
  }

  // 3. confidence and the physics check
  r.heading('Confidence & Verification');
  r.rows(model.verification);
  r.subheading('Physics check');
  r.rows(model.physics);
  r.text(model.physicsNote, { font: 'italic', size: 8.5, color: MUTED, gap: 4 });

  // 4. geodetic evidence, with the map snapshot the report is self-contained on
  r.heading('Geodetic Evidence');
  if (model.geodetic.withheld) {
    r.text(`coordinates withheld — ${model.geodetic.reason?.source || 'scene is not georeferenced'}`, {
      font: 'bold',
      size: 10,
      color: [0.55, 0.35, 0.05],
      gap: 4
    });
    r.text('No lat/lon, area or UTM figure is printed for a scene whose own metadata carries no CRS.', { gap: 4 });
  } else {
    r.rows(model.geodetic.rows);
    r.text(PROVENANCE.derived.aoi_area, { font: 'italic', size: 8.5, color: MUTED, gap: 4 });
  }
  if (model.snapshot?.bytes) {
    await r.image(model.snapshot.bytes, {
      caption: model.snapshotNote,
      mediaType: model.snapshot.mediaType || 'image/png'
    });
  }
  else r.text(model.snapshotNote, { font: 'italic', size: 8.5, color: MUTED, gap: 6 });

  // 5. the trace, numbered: what makes the report auditable
  r.heading('Execution Trace');
  if (model.trace.length) {
    r.numbered(model.trace);
    r.text(`${model.trace.length} steps · sources and values as shown in the execution trace panel`, {
      font: 'italic',
      size: 8.5,
      color: MUTED,
      gap: 4
    });
  } else {
    r.text('no trace recorded for this answer', { color: MUTED });
  }

  // 6. cross-reference to the geometry export
  r.rule({ gap: 10 });
  r.text(
    model.geojson.withheld
      ? `Geometry cross-reference: not written — ${model.geojson.reason}`
      : `Geometry cross-reference: ${model.geojson.filename}`,
    { font: 'mono', size: 8.5, color: MUTED, gap: 2 }
  );

  r.finish();
  return doc.save();
}

/**
 * The app-side entry point: snapshot in, downloaded file out. The caller owns
 * the snapshot (it needs the live viewer), so a report still composes when the
 * snapshot could not be taken — it says so instead of failing.
 */
export async function exportAnswerPDF({
  payload,
  query = null,
  geo,
  centroid = null,
  aoiPoints = [],
  scenes = [],
  raster = null,
  snapshot = null,
  snapshotNote = null,
  now = new Date()
}) {
  const model = buildReportModel({ payload, query, geo, centroid, aoiPoints, scenes, raster, snapshot, snapshotNote, now });
  const bytes = await buildReportPdf(model);
  const filename = reportFilename(payload?.question);
  downloadBytes(bytes, filename, 'application/pdf');
  return { filename, model };
}
