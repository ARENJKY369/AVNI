// Result report — the printable PDF field document, composed in the browser.
//
// The report is assembled from the *same* objects the answer card renders: the
// answer payload (answer_text, confidence, physics_check, geodetic, trace), the
// georeference block, the drawn AOI and the scene records. Nothing is recomputed
// here and nothing is invented — where the console withholds a value (an
// unlocated scene, a raster that never declared its size) the report says so in
// the same words the UI uses.
//
// Layout is deliberate: light paper, dark ink, serif body text, monospace for
// coordinates and numeric values, so a printed copy reads like a field document
// rather than a screenshot of the dark console. pdf-lib is imported lazily —
// nobody pays for the PDF writer until they ask for a PDF.
//
// The standard PDF fonts are WinAnsi-encoded, so any character outside CP1252
// (σ, ≈, → …) is transliterated before it reaches the page: a report must not
// fail to generate because an answer used a Greek letter.

import {
  PROVENANCE,
  aoiAreaHa,
  aoiAreaKm2,
  extentKm,
  fmtLat,
  fmtLon,
  gsdLabel,
  isGeoreferenced,
  placeSummary,
  utmBlock,
  withheldGeodetic
} from './geo.js';
import { ABSTAIN_GATE } from './model.js';
import { downloadBytes, slug } from './export.js';

export const REPORT_TITLE = 'AVNI · result report';
export const REPORT_MODEL = 'AVNI-VL 0.9';
export const REPORT_BUILD = 'SIH 26167 · SAC/ISRO';
/** The note the footer carries, in the words the operator asked for. */
export const REPORT_NOTE = 'Generated by SatQuery AI';

// The characters CP1252 carries outside Latin-1. Em dashes and curly quotes live
// here: filtering on "code point <= 0xFF" turned every one of them into a
// question mark in the middle of a sentence.
const CP1252_EXTRAS = new Set(
  '\u20ac\u201a\u0192\u201e\u2026\u2020\u2021\u02c6\u2030\u0160\u2039\u0152\u017d\u2018\u2019\u201c\u201d\u2022\u2013\u2014\u02dc\u2122\u0161\u203a\u0153\u017e\u0178'
);

const GLYPH_TRANSLITERATION = [
  ['ΔT', 'dT'],
  ['−', '-'], // U+2212 minus: the answer bank writes negative dB with it
  ['‑', '-'],
  ['σ', 'sigma'],
  ['Σ', 'Sigma'],
  ['δ', 'delta'],
  ['Δ', 'delta'],
  ['≈', '~'],
  ['≥', '>='],
  ['≤', '<='],
  ['→', '->'],
  ['↔', '<->'],
  ['√', 'sqrt'],
  ['⁻', '-'],
  ['⁰', '0'],
  ['¹', '1'],
  ['✓', 'v'],
  ['✗', 'x'],
  ['⁄', '/']
];

/**
 * WinAnsi-safe text. Anything CP1252 cannot carry is transliterated, and any
 * remaining non-Latin-1 character becomes "?" rather than throwing inside the
 * font encoder (which would lose the whole export).
 */
export function sanitize(value) {
  let s = String(value ?? '');
  for (const [from, to] of GLYPH_TRANSLITERATION) s = s.split(from).join(to);
  // code-point filter rather than a character-class regex: the class would need
  // control characters in it just to keep the newlines the layout relies on
  let out = '';
  for (const ch of s) out += ch.codePointAt(0) <= 0xff || CP1252_EXTRAS.has(ch) ? ch : '?';
  return out;
}

/** "MG Road 0.4 km NE · Bengaluru" — the place line the header shows. */
const aoiPlace = (centroid) => {
  const p = placeSummary(centroid.lat, centroid.lon);
  return p.region ? `${p.short} · ${p.region}` : p.short;
};

const isoDay = (d) => d.toISOString().replace('T', ' ').replace(/\.\d+Z$/, ' UTC');
const dayOnly = (v) => (v ? String(v).replace('T', ' ').replace(/\.\d+Z?$/, 'Z') : null);

export const reportFilename = (question) => `avni_report_${slug(question || 'result')}.pdf`;
/** The geometry file this report cross-references, same slug as the export. */
export const geojsonFilename = (question) => `avni_answer_${slug(question || 'result')}.geojson`;

/**
 * Everything the document prints, as data. Kept separate from the drawing code
 * so a test can assert that each value on the page came from the payload.
 */
export function buildReportModel({
  payload,
  query = null,
  geo,
  centroid = null,
  aoiPoints = [],
  scenes = [],
  raster = null,
  snapshot = null,
  snapshotNote = null,
  now = new Date()
} = {}) {
  const georef = isGeoreferenced(geo);
  const conf = payload?.confidence || {};
  const pc = payload?.physics_check || {};
  const g = payload?.geodetic || {};
  const utm = georef && centroid ? utmBlock(centroid.lat, centroid.lon) : null;
  const aoiKm2 = georef && aoiPoints.length > 2 ? aoiAreaKm2(aoiPoints, geo) : null;
  const aoiHa = georef && aoiPoints.length > 2 ? aoiAreaHa(aoiPoints, geo) : null;

  const header = [
    {
      label: 'area of interest',
      value: georef && centroid ? aoiPlace(centroid) : 'scene not georeferenced',
      mono: false
    },
    {
      label: 'AOI centroid',
      value: georef && centroid ? `${fmtLat(centroid.lat)} ${fmtLon(centroid.lon)}` : 'coordinates withheld',
      mono: true
    },
    { label: 'query raised', value: query?.at ? isoDay(new Date(query.at)) : 'not recorded for this session', mono: true },
    { label: 'session', value: `${REPORT_MODEL} · ${REPORT_BUILD}`, mono: false }
  ];

  const sceneRows = scenes.map((s) => ({
    role: s.role,
    file: s.file || 'unnamed',
    detail: [s.sensor, s.label].filter(Boolean).join(' · '),
    acquired: s.acquired ? dayOnly(s.acquired) : 'acquisition date not reported in the file'
  }));

  const verification = [
    { label: 'consistency score', value: conf.consistency_score != null ? Number(conf.consistency_score).toFixed(2) : 'not reported' },
    { label: 'gate', value: conf.abstained ? `declined — below ${ABSTAIN_GATE}` : `passed — at or above ${ABSTAIN_GATE}` },
    { label: 'reason', value: conf.reason || 'not reported' }
  ];

  const physics = [
    { label: 'NDWI', value: pc.ndwi != null ? `${Number(pc.ndwi).toFixed(2)} (water gate 0.45)` : 'not reported' },
    {
      label: 'SAR backscatter',
      value: pc.sar_backscatter_db != null ? `${Number(pc.sar_backscatter_db).toFixed(1)} dB` : 'not reported'
    },
    { label: 'verdict', value: pc.verdict || 'not reported' },
    { label: 'flag', value: pc.flagged ? 'flagged — readings disagree' : 'clear' }
  ];

  const geodetic = georef
    ? [
        { label: 'CRS', value: geo.crs || 'not stated' },
        { label: 'AOI area', value: aoiHa != null ? `${aoiHa.toFixed(1)} ha (${aoiKm2.toFixed(2)} km²)` : 'no AOI ring drawn' },
        { label: 'AOI vertices', value: aoiPoints.length ? `${aoiPoints.length}` : 'none' },
        { label: 'footprint area (fixture)', value: g.area_ha != null ? `${Number(g.area_ha).toFixed(1)} ha` : 'not reported' },
        { label: 'UTM', value: utm ? `${utm.zone} · ${utm.easting_m.toFixed(0)} E ${utm.northing_m.toFixed(0)} N` : 'not reported' },
        {
          label: 'footprint width',
          value: (() => {
            const { widthKm, heightKm } = extentKm(geo.extent);
            return `${widthKm.toFixed(2)} km x ${heightKm.toFixed(2)} km`;
          })()
        },
        { label: 'ground sample distance', value: raster?.width > 0 ? gsdLabel(geo.extent, raster) : 'not reported — the scene did not declare a raster size' },
        { label: 'georeference', value: geo.source || 'not stated' }
      ]
    : [];

  return {
    title: REPORT_TITLE,
    note: REPORT_NOTE,
    now,
    generatedAt: isoDay(now),
    generatedLabel: `${REPORT_MODEL} · ${REPORT_BUILD}`,
    header,
    scenes: sceneRows,
    question: payload?.question || 'no question recorded',
    intent: payload?.intent || null,
    answer: {
      abstained: !!conf.abstained,
      text: payload?.answer_text || null,
      gate: ABSTAIN_GATE,
      reason: conf.reason || null
    },
    verification,
    physics,
    physicsNote: `${PROVENANCE.fixture.physics_check} · scale and marker positions derived`,
    geodetic: { withheld: !georef, rows: geodetic, reason: georef ? null : withheldGeodetic(geo) },
    trace: (payload?.trace || []).map((t, i) => ({ n: i + 1, step: t.step, source: t.source, value: t.value || null })),
    snapshot,
    snapshotNote: snapshot
      ? snapshot.caption
      : snapshotNote || 'map snapshot unavailable — no decodable scene on screen when the report was composed',
    geojson: georef
      ? { filename: geojsonFilename(payload?.question), withheld: false }
      : { filename: null, withheld: true, reason: 'no geometry written — scene is not georeferenced' }
  };
}

